// Retorna o versículo do dia baseado no dia do ano
export const getVersiculoDoDia = () => {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % VERSICULOS_BIBLICOS.length;
  return { versiculo: VERSICULOS_BIBLICOS[index], index };
};

// Retorna um versículo aleatório
export const getVersiculoAleatorio = (currentIndex = -1) => {
  let newIndex = Math.floor(Math.random() * VERSICULOS_BIBLICOS.length);
  if (currentIndex >= 0 && VERSICULOS_BIBLICOS.length > 1) {
    while (newIndex === currentIndex) {
      newIndex = Math.floor(Math.random() * VERSICULOS_BIBLICOS.length);
    }
  }
  return { versiculo: VERSICULOS_BIBLICOS[newIndex], index: newIndex };
};
